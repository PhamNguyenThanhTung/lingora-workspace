const db=new PrismaClient({datasources:{db:{url:validateOwnedDatabaseUrl().ownedUrl}}});
after(async()=>{setLearnerPrismaForTest(null);await db.$disconnect();});
async function finish(f){
 const attemptId=randomUUID(),operationKey=randomUUID();
 await startPracticeAttempt(f.ctxA,f.lesson,{attemptId,expectedPublishedRevisionId:f.revision},f.learnerA);
 await submitPracticeResponse(f.ctxA,f.lesson,attemptId,{operationKey:randomUUID(),lessonExerciseId:f.exerciseId,input:{optionId:'opt-1'}},f.learnerA);
 return {result:await finalizePracticeAttempt(f.ctxA,f.lesson,attemptId,{operationKey},f.learnerA),attemptId,operationKey};
}
test('last required published lesson advances one level atomically and receipt replay never advances again',async()=>{
 const f=await createPracticeFixture(db);
 await db.level.update({where:{id:f.level},data:{code:'N5'}});
 const next=await db.level.create({data:{frameworkId:f.framework,code:'N4',label:{vi:'N4'},position:2}});
 const unit=await db.unit.create({data:{courseId:f.course,levelId:next.id,code:'NEXT',names:{vi:'N4'},position:1}});
 const created=await createLesson(f.admin,f.course,unit.id,{position:1,isRequired:true},db);assert.equal(created.status,201);
 const nextLesson=created.data.data.id;
 let row=await db.lesson.findUnique({where:{id:nextLesson}});
 assert.equal((await assignLesson(f.admin,f.course,unit.id,nextLesson,{teacherId:f.teacher,expectedRowVersion:String(row.rowVersion)},db)).status,200);
 row=await db.lesson.findUnique({where:{id:nextLesson}});
 const saved=await saveTeacherLessonDraft(f.teacher,nextLesson,{expectedRowVersion:String(row.rowVersion),title:{vi:'N4 lesson'},contentBlocks:[{type:'paragraph',text:'N4 reading'}],exercises:[{position:1,isCore:true,type:'MCQ',promptData:{prompt:'Choose',options:[{id:'yes',text:'Yes'},{id:'no',text:'No'}]},gradingData:{correctOptionId:'yes'}}],vocabulary:[]},db);assert.equal(saved.status,200,JSON.stringify(saved.error));
 let rev=saved.data.data.highestRevision;row=await db.lesson.findUnique({where:{id:nextLesson}});
 const submission=await submitTeacherLesson(f.teacher,nextLesson,{revisionId:rev.id,expectedLessonRowVersion:String(row.rowVersion),expectedRevisionRowVersion:String(rev.rowVersion)},db);assert.equal(submission.status,200,JSON.stringify(submission.error));
 rev=await db.lessonRevision.findUnique({where:{id:rev.id}});
 assert.equal((await approveReview(f.admin,submission.data.submissionId,{expectedRevisionRowVersion:String(rev.rowVersion)},db)).status,200);
 row=await db.lesson.findUnique({where:{id:nextLesson}});rev=await db.lessonRevision.findUnique({where:{id:rev.id}});
 assert.equal((await publishReview(f.admin,submission.data.submissionId,{expectedLessonRowVersion:String(row.rowVersion),expectedRevisionRowVersion:String(rev.rowVersion),makeAvailable:true},db)).status,200);
 await db.$transaction(async tx => { const context=await ownedContext(tx,f.ctxA,f.learnerA);assert.equal(await advanceCompletedLevel(tx,context),null,'unfinished required lesson must prevent advancement'); });
 setLearnerPrismaForTest(db);
 const before=await db.learningContext.findUnique({where:{id:f.ctxA}});
 const done=await finish(f);
 assert.deepEqual(done.result.levelUp,{from:{id:f.level,code:'N5'},to:{id:next.id,code:'N4'}});
 const context=await db.learningContext.findUnique({where:{id:f.ctxA}});
 assert.equal(context.workingLevelId,next.id);assert.equal(context.rowVersion,before.rowVersion+1n);
 const replay=await finalizePracticeAttempt(f.ctxA,f.lesson,done.attemptId,{operationKey:done.operationKey},f.learnerA);
 assert.deepEqual(replay.levelUp,done.result.levelUp);
 assert.equal((await db.learningContext.findUnique({where:{id:f.ctxA}})).rowVersion,context.rowVersion);
 const path=await buildLearningPath(db,f.ctxA,f.learnerA);
 assert.equal(path.currentLevel.code,'N4');assert.equal(path.sections.find(s=>s.levelId===f.level).progress.requiredDone,1);
 assert.notEqual(path.path.find(node=>node.lessonId===nextLesson).state,'LOCKED');
 assert.equal(await db.learnerAchievement.count({where:{learnerId:f.learnerA,achievementCode:'LEVEL_COMPLETED'}}),0);
});
test('next level without published content means no progression and preserves rowVersion',async()=>{
 const f=await createPracticeFixture(db);setLearnerPrismaForTest(db);
 await db.level.create({data:{frameworkId:f.framework,code:'NEXT_EMPTY',label:{vi:'Empty'},position:2}});
 const before=await db.learningContext.findUnique({where:{id:f.ctxA}});
 const done=await finish(f);assert.equal(done.result.levelUp,null);
 const after=await db.learningContext.findUnique({where:{id:f.ctxA}});
 assert.equal(after.workingLevelId,f.level);
 assert.equal(after.rowVersion,before.rowVersion,'finalize without level advancement must not increment rowVersion');
});
test('finalize preserves rowVersion until all required lessons in level are completed, then increments by 1',async()=>{
 const f=await createPracticeFixture(db);setLearnerPrismaForTest(db);
 await db.level.update({where:{id:f.level},data:{code:'A1'}});
 const next=await db.level.create({data:{frameworkId:f.framework,code:'A2',label:{vi:'A2'},position:2}});
 const nextUnit=await db.unit.create({data:{courseId:f.course,levelId:next.id,code:'A2-U1',names:{vi:'A2'},position:1}});
 const publishRequiredLesson=async(unitId,position,title)=>{
  const created=await createLesson(f.admin,f.course,unitId,{position,isRequired:true},db);assert.equal(created.status,201);
  const lessonId=created.data.data.id;
  let row=await db.lesson.findUnique({where:{id:lessonId}});
  assert.equal((await assignLesson(f.admin,f.course,unitId,lessonId,{teacherId:f.teacher,expectedRowVersion:String(row.rowVersion)},db)).status,200);
  row=await db.lesson.findUnique({where:{id:lessonId}});
  const saved=await saveTeacherLessonDraft(f.teacher,lessonId,{expectedRowVersion:String(row.rowVersion),title:{vi:title},contentBlocks:[{type:'paragraph',text:title}],exercises:[{position:1,isCore:true,type:'MCQ',promptData:{prompt:'Choose',options:[{id:'yes',text:'Yes'},{id:'no',text:'No'}]},gradingData:{correctOptionId:'yes'}}],vocabulary:[]},db);assert.equal(saved.status,200);
  let rev=saved.data.data.highestRevision;row=await db.lesson.findUnique({where:{id:lessonId}});
  const sub=await submitTeacherLesson(f.teacher,lessonId,{revisionId:rev.id,expectedLessonRowVersion:String(row.rowVersion),expectedRevisionRowVersion:String(rev.rowVersion)},db);assert.equal(sub.status,200);
  rev=await db.lessonRevision.findUnique({where:{id:rev.id}});
  assert.equal((await approveReview(f.admin,sub.data.submissionId,{expectedRevisionRowVersion:String(rev.rowVersion)},db)).status,200);
  row=await db.lesson.findUnique({where:{id:lessonId}});rev=await db.lessonRevision.findUnique({where:{id:rev.id}});
  assert.equal((await publishReview(f.admin,sub.data.submissionId,{expectedLessonRowVersion:String(row.rowVersion),expectedRevisionRowVersion:String(rev.rowVersion),makeAvailable:true},db)).status,200);
  const ex=await db.lessonExercise.findFirst({where:{lessonRevisionId:rev.id}});
  return {lessonId,revisionId:rev.id,exerciseId:ex.id};
 };
 const secondInA1=await publishRequiredLesson(f.unit,2,'A1 lesson 2');
 await publishRequiredLesson(nextUnit.id,1,'A2 lesson 1');
 const v0=(await db.learningContext.findUnique({where:{id:f.ctxA}})).rowVersion;
 const firstDone=await finish(f);
 assert.equal(firstDone.result.levelUp,null);
 const afterFirst=await db.learningContext.findUnique({where:{id:f.ctxA}});
 assert.equal(afterFirst.workingLevelId,f.level);
 assert.equal(afterFirst.rowVersion,v0,'rowVersion must stay unchanged when finalize does not level up');
 const secondAttemptId=randomUUID(),secondOpKey=randomUUID();
 await startPracticeAttempt(f.ctxA,secondInA1.lessonId,{attemptId:secondAttemptId,expectedPublishedRevisionId:secondInA1.revisionId},f.learnerA);
 await submitPracticeResponse(f.ctxA,secondInA1.lessonId,secondAttemptId,{operationKey:randomUUID(),lessonExerciseId:secondInA1.exerciseId,input:{optionId:'yes'}},f.learnerA);
 const secondDone=await finalizePracticeAttempt(f.ctxA,secondInA1.lessonId,secondAttemptId,{operationKey:secondOpKey},f.learnerA);
 assert.deepEqual(secondDone.levelUp,{from:{id:f.level,code:'A1'},to:{id:next.id,code:'A2'}});
 const afterSecond=await db.learningContext.findUnique({where:{id:f.ctxA}});
 assert.equal(afterSecond.workingLevelId,next.id);
 assert.equal(afterSecond.rowVersion,v0+1n,'rowVersion must increment by exactly 1 when finalize levels up');
});
test('profile CAS trims a valid name, rejects stale updates and cannot modify role',async()=>{
 const f=await createPracticeFixture(db);const before=await db.account.findUnique({where:{id:f.learnerA}});
 const result=await patchLearnerProfile(f.learnerA,{displayName:'  Mai  ',expectedRowVersion:String(before.rowVersion)},db);
 assert.equal(result.displayName,'Mai');
 await assert.rejects(()=>patchLearnerProfile(f.learnerA,{displayName:'Other',expectedRowVersion:String(before.rowVersion)},db),e=>e.status===409);
 for(const displayName of ['', 'a'.repeat(41),'Mai\nLan'])await assert.rejects(()=>patchLearnerProfile(f.learnerA,{displayName,expectedRowVersion:result.rowVersion},db),e=>e.status===400);
 const after=await db.account.findUnique({where:{id:f.learnerA}});assert.equal(after.role,'LEARNER');assert.equal(after.displayName,'Mai');
});

